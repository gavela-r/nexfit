export interface ProductColor {
  value: string;
  /** Clases extra (p. ej. borde para el color blanco). */
  className?: string;
}

export interface Product {
  id: string;
  name: string;
  category: string;
  rating: number;
  badge: { label: string; className: string };
  image: string;
  favorited: boolean;
  sizes: string[];
  defaultSize: string;
  colors: ProductColor[];
  price: number;
  originalPrice?: number;
  /** Slug de la categoría (futbol, running...). */
  categorySlug?: string;
  audience?: Audience;
  /** Tipo de prenda: camiseta, pantalon, short, chaqueta, sudadera, compresion, top, vestido, accesorio. */
  garmentType?: string;
  /**
   * Propiedades técnicas: compresion, ripstop, dwr, antiabrasion (hombre) y
   * squatproof, dryfit, cintura_alta (mujer), reflectante y french_terry,
   * oversize, bolsillos_zip, antipilling (athleisure).
   */
  features?: string[];
  /** Línea superior de la tarjeta: «Running · Clima Adverso». */
  subtitle?: string;
  description?: string;
}

export type Audience = "hombre" | "mujer" | "unisex";

const BADGE_BASE =
  "absolute top-3.5 left-3.5 z-10 text-[11px] uppercase tracking-wider font-extrabold px-2.5 py-1 rounded-full shadow-sm";

/** Mismas clases que traduce el backend a partir de badge_tone. */
const BADGE_CLASS = {
  nuevo: `${BADGE_BASE} bg-secondary text-white`,
  oferta: `${BADGE_BASE} bg-primary text-white`,
  tecnico: `${BADGE_BASE} bg-slate-900 dark:bg-slate-700 text-white`,
  bestseller: `${BADGE_BASE} bg-slate-900 dark:bg-slate-700 text-white`,
  tendencia: `${BADGE_BASE} bg-slate-200 dark:bg-slate-700 text-slate-800 dark:text-white`,
  soporte: `${BADGE_BASE} bg-primary text-white`,
} as const;

type BadgeTone = keyof typeof BADGE_CLASS;

/** Tonos claros que necesitan borde en la muestra de color (has_border en la BD). */
const LIGHT_COLORS = new Set(["#FFFFFF", "#E5E0D8"]);

interface CollectionProductSeed extends Omit<
  Product,
  "badge" | "favorited" | "audience" | "colors"
> {
  badge: [label: string, tone: BadgeTone];
  colors: string[];
}

/** Prenda de una colección Hombre / Mujer (mismos datos que nexfit.sql). */
function collectionProduct(
  audience: Audience,
  { badge, colors, ...rest }: CollectionProductSeed,
): Product {
  return {
    ...rest,
    audience,
    favorited: false,
    badge: { label: badge[0], className: BADGE_CLASS[badge[1]] },
    colors: colors.map((value) =>
      LIGHT_COLORS.has(value) ? { value, className: "border border-slate-300" } : { value },
    ),
  };
}

const menProduct = (seed: CollectionProductSeed) => collectionProduct("hombre", seed);
const womenProduct = (seed: CollectionProductSeed) => collectionProduct("mujer", seed);

